// Development-only asset refresh. The application never requests remote fonts.
import { createHash } from 'node:crypto'
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'

const source = fileURLToPath(new URL('../src/', import.meta.url))
const output = fileURLToPath(new URL('../src/assets/fonts/', import.meta.url))
const characters = new Set()
async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) await collect(path)
    else if (/\.(ts|tsx)$/.test(entry.name) && !/\.(test|spec)\./.test(entry.name)) {
      for (const character of (await readFile(path, 'utf8')).match(/[\p{Script=Han}\u3000-\u303f\uff00-\uffef\u2000-\u206f]/gu) ?? []) characters.add(character)
    }
  }
}
await collect(source)
const sorted = [...characters].sort((a, b) => a.codePointAt(0) - b.codePointAt(0))
const chunks = [Array.from({ length: 95 }, (_, i) => String.fromCodePoint(32 + i)).join('')]
for (let i = 0; i < sorted.length; i += 240) chunks.push(sorted.slice(i, i + 240).join(''))
await mkdir(output, { recursive: true })
const faces = [], files = []
for (const chunk of chunks) {
  const url = new URL('https://fonts.googleapis.com/css2')
  url.searchParams.set('family', 'Noto Sans SC:wght@400..700')
  url.searchParams.set('display', 'swap')
  url.searchParams.set('text', chunk)
  const response = await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/132.0.0.0 Safari/537.36' }, signal: AbortSignal.timeout(30000) })
  if (!response.ok) throw new Error(`Font stylesheet: HTTP ${response.status}`)
  const css = await response.text()
  const fontUrl = css.match(/src:\s*url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)\s*format\('woff2'\)/)?.[1]
  if (!fontUrl) throw new Error('Expected an official WOFF2 font source')
  const fontResponse = await fetch(fontUrl, { signal: AbortSignal.timeout(30000) })
  if (!fontResponse.ok) throw new Error(`Font asset: HTTP ${fontResponse.status}`)
  const data = Buffer.from(await fontResponse.arrayBuffer())
  if (data.subarray(0, 4).toString() !== 'wOF2') throw new Error('Invalid WOFF2 asset')
  const name = `inkloom-ui-${createHash('sha256').update(data).digest('hex').slice(0, 12)}.woff2`
  await writeFile(join(output, name), data)
  const range = [...chunk].map(c => `U+${c.codePointAt(0).toString(16).toUpperCase()}`).join(',')
  faces.push(`@font-face {\n  font-family: 'Inkloom UI';\n  font-style: normal;\n  font-weight: 400 700;\n  font-display: swap;\n  src: url('./${name}') format('woff2');\n  unicode-range: ${range};\n}`)
  files.push({ name, bytes: data.length, source: fontUrl, characters: [...chunk].length })
}
const licenseUrl = 'https://raw.githubusercontent.com/google/fonts/main/ofl/notosanssc/OFL.txt'
const license = await fetch(licenseUrl, { signal: AbortSignal.timeout(30000) })
if (!license.ok) throw new Error(`Font license: HTTP ${license.status}`)
const licenseText = (await license.text()).replace(/[ \t]+$/gm, '')
await writeFile(join(output, 'OFL-NotoSansSC.txt'), licenseText)
const bundledLicense = fileURLToPath(new URL('../public/assets/fonts/', import.meta.url))
await mkdir(bundledLicense, { recursive: true })
await writeFile(join(bundledLicense, 'OFL-NotoSansSC.txt'), licenseText)
await writeFile(join(output, 'ui-font.css'), `/* Generated by scripts/update-ui-font.mjs. Noto Sans SC, SIL OFL 1.1. */\n${faces.join('\n\n')}\n`)
await writeFile(join(output, 'manifest.json'), `${JSON.stringify({ family: 'Noto Sans SC', upstream: 'https://github.com/google/fonts/tree/main/ofl/notosanssc', license: 'SIL OFL 1.1', licenseUrl, files }, null, 2)}\n`)
console.log(`${files.length} local font subsets; ${sorted.length} UI characters; ${files.reduce((sum, file) => sum + file.bytes, 0)} bytes`)
