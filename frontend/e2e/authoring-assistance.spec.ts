import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { resolve } from 'node:path'

async function fixture(page: Page, confirmed = false) {
  await page.goto('/')
  await expect(page.getByRole('button', { name: '新建小说', exact: true })).toBeVisible()
  return page.evaluate(async confirmed => {
    const health = await (await fetch('/api/v1/health')).json()
    if (!health.workspace_name.startsWith('e2e-')) throw new Error('Refusing author workspace')
    async function write(path: string, body: object, method = 'POST') {
      const response = await fetch('/api/v1' + path, { method, headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) })
      if (!response.ok) throw new Error(`Authoring fixture ${response.status}: ${await response.text()}`)
      return response.json()
    }
    const novel = await write('/novels', { title: '灯塔来信 · 创作辅助', premise: '林舟循着来信寻找父亲，守塔人掌握下一条线索。' })
    const path = `/novels/${novel.id}`
    const first = await write(path + '/chapters', { title: '第一章', goal: '林舟争取进入灯塔。' })
    const original = await write(path + `/chapters/${first.id}/versions`, { base_version_id: first.working_version_id, operation_id: crypto.randomUUID(), text: '林舟将钥匙交给守塔人。' })
    if (confirmed) await write(path + `/chapters/${first.id}/canon`, { version_id: original.id, operation_id: crypto.randomUUID(), changes: [] })
    const second = await write(path + '/chapters', { title: '第二章', goal: '守塔人带林舟上楼。' })
    if (confirmed) await write(path + `/chapters/${second.id}/references`, { base_revision: 0, selection: { entity_ids: [], chapters: [{ chapter_id: first.id, version_id: original.id }], notes: '' } }, 'PUT')
    const next = await write(path + `/chapters/${second.id}/versions`, { base_version_id: second.working_version_id, operation_id: crypto.randomUUID(), text: '守塔人把钥匙放进衣袋，打开了楼梯间。' })
    if (confirmed) await write(path + `/chapters/${second.id}/canon`, { version_id: next.id, operation_id: crypto.randomUUID(), changes: [] })
    await write(path + '/entities', { kind: 'character', name: '林舟', summary: '追查来信的归乡者。', body: '林舟愿意冒险换取父亲的下落。' })
    return { novel: novel.id as string, chapter: first.id as string, version: original.id as string,
      second: second.id as string, next: next.id as string }
  }, confirmed)
}

async function assistant(page: Page) {
  const opener = page.getByRole('button', { name: '打开写作助手', exact: true })
  if (await opener.isVisible()) await opener.click()
  return page.locator('.assistant-panel:visible')
}

test('选择正文与档案讨论，引用能回看版本，刷新保留选择且正文变化阻止旧提案', async ({ page }, testInfo) => {
  const ids = await fixture(page)
  await page.goto(`/#/plot/${ids.novel}?view=discuss`)
  await page.getByRole('button', { name: '新讨论', exact: true }).click()
  const region = page.getByRole('region', { name: '规划讨论', exact: true })
  const materials = region.locator('summary').filter({ hasText: '正文与档案' })
  await materials.click()
  await region.getByRole('checkbox', { name: '参考正文：第二章', exact: true }).check()
  await region.getByRole('checkbox', { name: '参考档案：林舟', exact: true }).check()
  await materials.click()
  await region.getByRole('textbox', { name: '讨论内容', exact: true }).fill('结合第二章正文和林舟档案，第一章交出钥匙的动机该怎么铺垫？请引用正文。')
  await region.getByRole('combobox', { name: '讨论模型', exact: true }).selectOption('demo')
  await region.getByRole('button', { name: '查看本次资料', exact: true }).click()
  const preview = page.getByRole('dialog', { name: '本次资料与费用估算', exact: true })
  await expect(preview).toContainText('守塔人把钥匙放进衣袋，打开了楼梯间。')
  await expect(preview).toContainText('追查来信的归乡者。')
  await preview.getByRole('button', { name: '关闭对话框', exact: true }).click()
  await region.getByRole('button', { name: '发送', exact: true }).click()
  const source = region.locator('.discussion-messages').getByRole('button').filter({ hasText: '第二章' })
  await expect(source).toBeVisible()
  await source.click()
  const evidence = page.getByRole('dialog', { name: '原文依据', exact: true })
  await expect(evidence).toContainText('守塔人把钥匙放进衣袋，打开了楼梯间。')
  await evidence.getByRole('button', { name: '关闭对话框', exact: true }).click()
  await page.reload()
  await materials.click()
  await expect(region.getByRole('checkbox', { name: '参考正文：第二章', exact: true })).toBeChecked()
  await expect(region.getByRole('checkbox', { name: '参考档案：林舟', exact: true })).toBeChecked()
  await materials.click()
  const scan = await new AxeBuilder({ page }).include('.planning-discussions').withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(scan.violations.map(item => item.id)).toEqual([])
  await page.screenshot({ path: resolve(`../docs/screenshots/authoring-discussion-${testInfo.project.name}.png`) })
  await page.evaluate(async ids => {
    const response = await fetch(`/api/v1/novels/${ids.novel}/chapters/${ids.second}/versions`, { method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ base_version_id: ids.next, operation_id: crypto.randomUUID(), text: '守塔人拒绝接过钥匙，转身锁上楼梯间。' }) })
    if (!response.ok) throw new Error(`Concurrent manuscript save: ${response.status}`)
  }, ids)
  await region.getByRole('button', { name: '查看并采纳', exact: true }).click()
  const proposal = page.getByRole('dialog', { name: '讨论中的细纲修改建议', exact: true })
  await expect(proposal).toContainText('已变化')
  await expect(proposal.getByRole('button', { name: '采纳所选修改', exact: true })).toBeDisabled()
})

test('按场景生成候选，作者采纳后追加正文并保留原稿', async ({ page }, testInfo) => {
  const ids = await fixture(page)
  await page.goto(`/#/write/${ids.novel}/${ids.chapter}`)
  await expect(page.getByRole('textbox', { name: '小说正文', exact: true })).toContainText('林舟将钥匙交给守塔人。')
  const panel = await assistant(page)
  await panel.getByRole('button', { name: '写一个场景', exact: true }).click()
  await expect(panel.getByRole('button', { name: '生成场景草稿', exact: true })).toBeDisabled()
  await panel.getByRole('textbox', { name: '本场要发生什么', exact: true }).fill('林舟与守塔人交涉，争取进入灯塔。')
  await panel.getByRole('textbox', { name: '阻碍或冲突', exact: true }).fill('守塔人不肯放行，要求林舟证明来意。')
  await panel.getByText('转折、收束与视角', { exact: true }).click()
  await panel.getByRole('textbox', { name: '写到哪里停', exact: true }).fill('停在守塔人提出条件的时候。')
  await page.screenshot({ path: resolve(`../docs/screenshots/scene-writing-${testInfo.project.name}.png`) })
  await panel.getByRole('button', { name: '生成场景草稿', exact: true }).click()
  const adopt = page.getByRole('button', { name: '采纳正文', exact: true })
  await expect(adopt).toBeVisible()
  const original = await page.evaluate(async ids => (await (await fetch(`/api/v1/novels/${ids.novel}/chapters/${ids.chapter}`)).json()).version.text, ids)
  expect(original).toBe('林舟将钥匙交给守塔人。')
  await adopt.click()
  const saved = await page.evaluate(async ids => (await (await fetch(`/api/v1/novels/${ids.novel}/chapters/${ids.chapter}`)).json()).version.text, ids)
  expect(saved.startsWith(original)).toBe(true)
  expect(saved.length).toBeGreaterThan(original.length)
  const previous = await page.evaluate(async ids => (await (await fetch(`/api/v1/novels/${ids.novel}/chapters/${ids.chapter}/versions/${ids.version}`)).json()).text, ids)
  expect(previous).toBe(original)
})

test('改前文后查看复核清单，按需比较并按顺序定位，不自动确认后章', async ({ page }, testInfo) => {
  const ids = await fixture(page, true)
  await page.goto(`/#/write/${ids.novel}/${ids.chapter}`)
  const editor = page.getByRole('textbox', { name: '小说正文', exact: true })
  await expect(editor).toContainText('林舟将钥匙交给守塔人。')
  await editor.fill('林舟把钥匙留在自己手里，要求守塔人先解释来信。')
  await expect(page.locator('.save-status')).toHaveText('已保存')
  const versionReads: string[] = []
  page.on('request', request => { if (/\/versions\/version_/.test(request.url())) versionReads.push(request.url()) })
  await page.getByRole('button', { name: '查看复核清单', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '改稿复核清单', exact: true })
  await expect(dialog).toContainText('2 章待复核')
  await expect(dialog).toContainText('必读前文《第一章》尚待复核')
  expect(versionReads).toHaveLength(0)
  await dialog.getByText('比较定稿与当前正文', { exact: true }).click()
  await expect(dialog.locator('.review-impact-comparison')).toContainText('林舟将钥匙交给守塔人。')
  await expect(dialog.locator('.review-impact-comparison')).toContainText('林舟把钥匙留在自己手里')
  expect(versionReads).toHaveLength(2)
  await page.screenshot({ path: resolve(`../docs/screenshots/review-impact-${testInfo.project.name}.png`) })
  const scan = await new AxeBuilder({ page }).include('[role="dialog"]').withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(scan.violations.map(item => item.id)).toEqual([])
  await dialog.getByRole('button', { name: '从最早待复核章开始', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: '本章定稿', exact: true }).click()
  const finalize = page.getByRole('dialog', { name: '本章定稿', exact: true })
  await finalize.getByRole('button', { name: '仅定稿', exact: true }).click()
  await expect(finalize).not.toBeVisible()
  await page.getByRole('button', { name: '查看复核清单', exact: true }).click()
  await expect(dialog).toContainText('1 章待复核')
  await expect(dialog).toContainText('已有新定稿，需重新选择参考')
  await dialog.getByRole('button', { name: '从最早待复核章开始', exact: true }).click()
  await expect(page.getByRole('heading', { name: '第二章', exact: true })).toBeVisible()
  const state = await page.evaluate(async ids => (await (await fetch(`/api/v1/novels/${ids.novel}/chapters/${ids.second}`)).json()).review_state, ids)
  expect(state).toBe('needs_review')
})
