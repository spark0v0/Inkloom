export function getPresetsByCategory(category: BrainstormCategory): BrainstormPreset[] {
  return BRAINSTORM_PRESETS.filter(p => p.category === category)
}

export function parseBrainstormText(text: string): string[] {
  if (!text.trim()) return []
  // Split by double newline or numbered items like "1. ", "1、", "【"
  const lines = text
    .split(/\n+/)
    .map(line => line.trim())
    .filter(line => line.length > 0)

  const items: string[] = []
  let current = ''

  for (const line of lines) {
    const isNewItem = /^(\d+[\.、\s]|[-*•]\s|【)/.test(line)
    if (isNewItem) {
      if (current.trim()) items.push(current.trim())
      current = line.replace(/^(\d+[\.、\s]|[-*•]\s)/, '')
    } else if (current) {
      current += '\n' + line
    } else {
      current = line
    }
  }

  if (current.trim()) items.push(current.trim())
  return items.length > 0 ? items : [text.trim()]
}
